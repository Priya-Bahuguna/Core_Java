package com.part3;

public class IntToDouble {
    public static void main(String[] args) {
        int a =34;
        double b = a;
        System.out.println(b);
        // double to int
        double c = 23.4;
        int d = (int) c;
        System.out.println(d);

        // take a decimal no. and print its integer parts using casting
        double s= 78.4;
        int m = (int) s;
        System.out.println(m);

        //convert int into float
        int r = 22;
        float f = (float)r;
        System.out.println(f);

        //char into int
        char ch='A';
        int w =  ch;
        System.out.println(w);

        //int gto char
        int k=66;
        char cp=(char)k;
        System.out.println(cp);

    }
}
