package com.part1;

public class EscapeSequence {
    public static void main(String[] args) {
        String name = "Priya Bahuguna";
        System.out.println("My name is:\t" + name);
        int age = 20;
        System.out.println("My age is:\t" + age);
        String course = "MCA";
        System.out.println("My course is:\t" + course);
    }
}
