package com.part1;

public class PrimitiveDatatypes2 {
    public static void main(String[] args) {
        int i=10;
        float f=10.0f;
        double d=10.0;
        char c='a';
        boolean b=true;
        System.out.println(i);
        System.out.println(f);
        System.out.println(d);
        System.out.println(c);
        System.out.println(b);
    }
}
